"""The miner's Cosmos keyring: which backend, which passphrase, and how `dendrad` is handed it.

THE BACKEND IS READ FROM THE STATE OF THE DISK, NEVER FROM A SETTING.
    keyring-test holds keys, keyring-file holds nothing   -> `test`, with a warning: the key is in clear
    keyring-file holds anything                           -> `file`, and the passphrase is REQUIRED
    both hold something                                   -> REFUSED: two keyrings are two possible
                                                             identities, and guessing picks one
    neither holds anything                                -> `file` when the passphrase FILE is there,
                                                             `test` otherwise, with the same warning
A setting could say `file` over a keyring that is `test` (or the reverse): `dendrad` would then look in a
directory that holds no key, the miner would find "no key", and create a NEW one -- a new address, a new
identity, an unfunded account, while the stake stays on chain under the old one. The disk cannot
disagree with itself.

WHERE THE PASSPHRASE COMES FROM. A file mounted READ-ONLY into the container
(`/run/dendra-secrets/keyring-passphrase`, `deploy/testnet-miner/docker-compose.yml`), generated by the kit
outside the miner-keys volume and outside the clone. Never argv (`ps` and `/proc/<pid>/cmdline` are
readable by every local process) and never an environment variable the kit hands the container
(`docker inspect` prints it). `DENDRA_MINER_PASSPHRASE` is still read OUTSIDE the container, as a
fallback, with a warning that says what it exposes.
It reaches `dendrad` on STDIN, one line per prompt. `dendrad keys add` on a keyring that has no passphrase
yet reads it twice (enter, re-enter), every other command once; a command never reads past what it asks
for, so every call is handed STDIN_COPIES lines.

WHAT IT PROTECTS, AND WHAT IT DOES NOT. An encrypted keyring protects the miner-keys volume and every
backup of it: a copy of the volume alone no longer holds a usable key. It does not protect a host that is
compromised while the miner runs: the passphrase sits next to the volume, on the same host, by design --
the miner restarts unattended.

THE ZERO RULE, ON A KEY. `dendrad` answers a wrong or missing passphrase with "<name> is not a valid name
or address: too many failed passphrase attempts", which reads like an absent key; and `dendrad keys list`
answers it with exit 0 and an EMPTY list. Taking either at its word, a miner that cannot open its keyring
would conclude it has no key and create one. So a key is ABSENT only when dendrad says so AND the disk
agrees (no `<name>.info` in the keyring directory); anything else is UNREADABLE, and nothing is created.

    python3 -m modea.keyring list                         every key, as `dendrad keys list --output json`
    python3 -m modea.keyring status <keydir>              keyring, recovery phrase, payout record (JSON)
    python3 -m modea.keyring recovery <file>              the kept recovery phrase, opened (JSON)
    python3 -m modea.keyring forget-recovery <file> --address A --yes   removes it; nothing without --yes
    python3 -m modea.keyring vrf-pubkey <file>            public key of a (possibly encrypted) VRF secret
    python3 -m modea.keyring plan <keydir> [--app-settings -]   what encrypt-keys.sh reads (key=value)
    python3 -m modea.keyring migrate <keydir> --yes       test -> file, same addresses verified
    python3 -m modea.keyring address <keydir>             identity, address and keys at rest (key=value)

THE ADDRESS IS READ HERE, NEVER IN THE LOGS. The daemon prints it once, at start ("ready  addr=..."), and the
kit ROTATES the container logs (deploy/testnet-miner/docker-compose.yml, `logging:`): a line printed once is
gone after enough traffic. `address` reads it from the keyring itself, running or stopped:
    docker compose -p dendra-miner exec -T miner python3 -m modea.keyring address /data/keys          (running)
    docker compose -p dendra-miner run --rm --no-deps -T --entrypoint python3 miner -m modea.keyring address /data/keys
"""
